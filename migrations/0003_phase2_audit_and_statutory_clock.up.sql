-- -----------------------------------------------------------------------------
-- 1. INCIDENT STATUTORY CLOCK (24-hour statutory countdown per Oman MoL MD 286/2008)
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS incident_statutory_clock (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    tenant_id UUID NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
    incident_id UUID NOT NULL REFERENCES incidents(id) ON DELETE CASCADE,
    started_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    due_at TIMESTAMPTZ NOT NULL,
    severity VARCHAR(32) NOT NULL,
    status VARCHAR(32) NOT NULL DEFAULT 'RUNNING',
    acknowledged_at TIMESTAMPTZ,
    acknowledged_by VARCHAR(255),
    submission_id UUID REFERENCES submissions(id) ON DELETE SET NULL,
    escalation_stage VARCHAR(32) NOT NULL DEFAULT 'INITIAL',
    last_escalated_at TIMESTAMPTZ,
    details JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_incident_statutory_clock_tenant ON incident_statutory_clock(tenant_id);
CREATE INDEX IF NOT EXISTS idx_incident_statutory_clock_incident ON incident_statutory_clock(incident_id);
CREATE INDEX IF NOT EXISTS idx_incident_statutory_clock_due ON incident_statutory_clock(due_at);
ALTER TABLE incident_statutory_clock ENABLE ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation_incident_statutory_clock ON incident_statutory_clock
    FOR ALL
    USING (tenant_id = current_setting('app.tenant_id')::uuid);

-- -----------------------------------------------------------------------------
-- 2. NOTIFICATION OUTBOX (Escalation events generated by statutory worker)
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS notification_outbox (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    tenant_id UUID NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
    event_type VARCHAR(64) NOT NULL,
    entity_type VARCHAR(64) NOT NULL,
    entity_id VARCHAR(128) NOT NULL,
    recipient_role VARCHAR(64) NOT NULL,
    payload JSONB NOT NULL DEFAULT '{}'::jsonb,
    status VARCHAR(32) NOT NULL DEFAULT 'PENDING',
    scheduled_for TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    sent_at TIMESTAMPTZ,
    error_message TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_notification_outbox_tenant ON notification_outbox(tenant_id);
CREATE INDEX IF NOT EXISTS idx_notification_outbox_status ON notification_outbox(status);
ALTER TABLE notification_outbox ENABLE ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation_notification_outbox ON notification_outbox
    FOR ALL
